"""
Нормализация названий моделей и цветов для сопоставления с каталогом.

В КП названия пишут как придётся, поэтому перед сравнением обе стороны
(строка из КП и запись каталога) приводятся к одной канонической форме.
Правила подобраны по реальным КП из `documentanions/`:

  • юникод приводится к NFC: macOS отдаёт имена папок в разложенном виде,
    где «й» — это «и» + надстрочный знак, и без NFC «серый» из каталога
    не совпадёт с «серый» из КП
  • регистр не важен:            «ОРЕХ» = «Орех»
  • ё = е:                       «Морёный дуб» = «Мореный дуб»
  • удвоенные буквы схлопываем:  «Капуччино» = «Капучино»
  • кириллические буквы-омоглифы → латиница (одинаково для обеих сторон),
    поэтому «Nord» из КП совпадёт с «Nord», набранным через кириллические
    «о» и «р», а «Орех» → «opex» с обеих сторон
  • пунктуация и лишние пробелы убираются:  «Piana 1 PG верт. 60мм» →
    «piana 1 pg bept 60m»

Модуль сознательно не зависит от Django — его можно звать из парсера,
команд импорта и тестов.
"""
import re
import unicodedata

# Кириллические буквы, визуально неотличимые от латинских. Складываем их
# в латиницу, чтобы «SKY»/«СКУ» и «Nord»/«Nоrd» приводились к одному виду.
_CONFUSABLES = str.maketrans({
    'а': 'a', 'в': 'b', 'е': 'e', 'к': 'k', 'м': 'm', 'н': 'h', 'о': 'o',
    'р': 'p', 'с': 'c', 'т': 't', 'у': 'y', 'х': 'x',
})

_DOUBLE_LETTER_RE = re.compile(r'(.)\1+')
_NON_ALNUM_RE = re.compile(r'[^0-9a-zа-я]+')
_SPACES_RE = re.compile(r'\s+')


def normalize(text: str) -> str:
    """Каноническая форма строки для сравнения с каталогом."""
    if not text:
        return ''
    result = unicodedata.normalize('NFC', str(text)).lower().replace('ё', 'е')
    # Схлопываем удвоения ДО подмены омоглифов: «капуччино» → «капучино».
    result = _DOUBLE_LETTER_RE.sub(r'\1', result)
    result = result.translate(_CONFUSABLES)
    result = _NON_ALNUM_RE.sub(' ', result)
    return _SPACES_RE.sub(' ', result).strip()
